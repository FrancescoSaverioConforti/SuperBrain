//! `run_cli` (B5.1 Task 15): the minimal CLI approval surface's logic,
//! extracted from the thin `examples/approve_cli.rs` binary so it is
//! testable as a library call (`crates/brain-api/tests/cli_approval_e2e.rs`)
//! without spawning a subprocess. Per the design doc's own scope limit —
//! "NON costruire la UI in B5; CLI approval minima se necessaria per
//! verificare E2E" — this is deliberately a 3-command (`list`/`approve`/
//! `reject`) surface, nothing more: no flags, no config file, no new error
//! category, no capability beyond the 12 frozen ones plus the
//! approve/reject pair Task 14 already implemented.
//!
//! **Trust boundary**: `run_cli` is itself the trusted local CLI entry
//! point the B5.0 contract's trust model names (`docs/superpowers/specs/
//! 2026-11-15-b5-0-brain-api-contract-freeze.md`'s "Only a trusted human
//! approval surface (CLI now; B6 UI later) may move a proposal to
//! Approved/Rejected"). It is the ONE place in this crate that constructs
//! `RequestContext { write_policy: Some(WritePolicy::trusted_cli()),
//! origin: CallOrigin::TrustedLocal(TrustedLocalToken::new()), .. }` —
//! never from `args`, never from any value this function receives from its
//! caller. `args` can only ever name a subcommand and a proposal id/reason;
//! there is no argument shape through which a caller could set
//! `write_policy` or `origin` to anything else, because this function's
//! own signature has no such parameter and builds the trusted context
//! itself, every call, unconditionally. Both `WritePolicy::trusted_cli`
//! and `TrustedLocalToken::new` are `pub(crate)` (B5 layering review): this
//! module is the only place in the crate's public surface that can reach
//! either, and nothing outside `brain-api` — including a future
//! `mcp-server` crate — can call either one at all.

use crate::audit::{allowed_from_result, record_permission_decision, record_tool_call, AuditSink, NullAuditSink};
use crate::{BrainApiError, CallOrigin, ProposalId, RequestContext, TrustedLocalToken, WritePolicy};

/// Closure shape for [`DurableApprovalHooks::record_outcome`] — factored
/// into its own alias purely to keep that field's and [`DurableApprovalHooks::noop`]'s
/// own signatures readable; carries no behavior of its own.
type RecordOutcomeFn<'a> = &'a mut dyn FnMut(uuid::Uuid, &Result<storage::CommitResult, BrainApiError>) -> Result<(), String>;

/// M5 Task 7: opaque, trust-blind hooks for the durable audit path around
/// one `approve` command — injected by [`run_cli_durable`]'s caller, which
/// owns the real async durable-acknowledgment worker (`brain-api-audit-
/// worker`, a crate this one has NO dependency on and never will: these
/// closures see only plain data, never `RequestContext`/`WritePolicy`/
/// `TrustedLocalToken`, so nothing here can construct, inspect, or
/// influence trust — see `tests/layering.rs`'s own
/// `run_cli_durables_hooks_are_trust_blind_and_cannot_influence_authorization`
/// for the compile-time + behavioral proof). Both fields are plain
/// synchronous `FnMut` from this crate's own point of view: `brain-api`
/// stays exactly as free of any async runtime dependency as it was before
/// this task — any bridging to a real async worker is entirely the
/// caller's concern (see `examples/approve_cli.rs`).
pub struct DurableApprovalHooks<'a> {
    /// Called exactly once, BEFORE [`crate::approve_proposal`] is ever
    /// invoked, with a fresh `attempt_id` (generated by [`run_cli_durable`]
    /// itself, never by the caller) and the target proposal's id as a
    /// plain string. `Err` refuses to proceed: `approve_proposal` is NEVER
    /// called in that case (fail-closed pre-registration) and
    /// [`run_cli_durable`] returns [`BrainApiError::RuntimeUnavailable`]
    /// carrying this message.
    pub pre_register: &'a mut dyn FnMut(uuid::Uuid, &str) -> Result<(), String>,
    /// Called exactly once, AFTER `approve_proposal` returns (whatever the
    /// outcome), with the SAME `attempt_id` and the real, already-decided
    /// `Result`. This call's own return value NEVER changes what
    /// [`run_cli_durable`] reports as the command's real result — see
    /// [`DurableCliOutcome::audit_outcome_write`] for where an `Err` here
    /// surfaces instead, as a separate, honest signal, never folded into
    /// or overwriting the commit's own truth.
    pub record_outcome: RecordOutcomeFn<'a>,
}

impl<'a> DurableApprovalHooks<'a> {
    /// The inert default both `run_approve`/`run_reject` (the existing,
    /// non-durable entry points) use internally — `pre_register` always
    /// succeeds immediately and `record_outcome` is never reached by
    /// those two paths at all (see [`run_approve_core`]'s own doc
    /// comment), so this never changes `run_cli`/`run_cli_with_audit`'s
    /// existing, byte-identical observable behavior.
    fn noop(pre_register: &'a mut dyn FnMut(uuid::Uuid, &str) -> Result<(), String>, record_outcome: RecordOutcomeFn<'a>) -> Self {
        Self { pre_register, record_outcome }
    }
}

/// [`run_cli_durable`]'s own result: the REAL command outcome (identical
/// truth to what [`run_cli_with_audit`] would have returned for the same
/// command and inputs) plus, separately, whether the durable
/// `CommitOutcome` write itself succeeded. `audit_outcome_write` is
/// `Ok(())` for every command that never reaches
/// [`DurableApprovalHooks::record_outcome`] at all (`list`, `reject`, or
/// an `approve` that never got past pre-registration) — it is
/// specifically about "did persisting the outcome event itself succeed",
/// never a proxy for whether the approval/commit itself succeeded, and
/// never discarded silently when it fails.
#[derive(Debug)]
pub struct DurableCliOutcome {
    pub result: Result<String, BrainApiError>,
    pub audit_outcome_write: Result<(), String>,
}

fn trusted_ctx() -> RequestContext {
    RequestContext {
        schema_version: crate::SCHEMA_VERSION,
        correlation_id: uuid::Uuid::new_v4(),
        write_policy: Some(WritePolicy::trusted_cli()),
        // This CLI surface only ever calls approve_proposal/reject_proposal/
        // list_proposals (Task 14/15) -- none of which check read_policy --
        // so it has no need for read permission. Left None (principle of
        // least privilege): this context can never be handed to search/
        // retrieve/get_code_context and have it silently succeed.
        read_policy: None,
        origin: CallOrigin::TrustedLocal(TrustedLocalToken::new()),
    }
}

/// Runs one CLI command against `vault`, returning a human-readable
/// result string on success. `now` is the caller's own timestamp source
/// (the thin example binary uses the real wall clock; tests use a fixed
/// string) — never parsed out of `args` itself.
///
/// Recognized commands (exactly these three; anything else is
/// `InvalidInput`, never a panic):
/// - `list`: lists every pending/expired-at-list-time proposal.
/// - `approve <id>`: approves and executes the named proposal.
/// - `reject <id> <reason>`: rejects the named proposal with `reason`.
pub fn run_cli(args: &[String], vault: &storage::Vault, now: &str) -> Result<String, BrainApiError> {
    run_cli_with_audit(args, vault, now, &NullAuditSink)
}

/// Same as [`run_cli`], recording one `ToolCall`/`PermissionDecision`/
/// `WriteMemory` event per command to `sink` (B5.12 Task 33) — `run_cli`
/// itself keeps its exact, separately-pinned `(args, vault, now)` signature
/// (`tests/layering.rs`'s own compile-time property test) and is now a
/// thin wrapper over this function with [`NullAuditSink`], so every
/// existing caller of `run_cli` is unaffected. Each command gets its own
/// fresh `correlation_id` (a CLI invocation has no `RequestContext` to
/// reuse across multiple commands the way one MCP tool call does — `list`/
/// `approve`/`reject` are each their own trusted-local call here).
pub fn run_cli_with_audit(args: &[String], vault: &storage::Vault, now: &str, sink: &dyn AuditSink) -> Result<String, BrainApiError> {
    let ctx = trusted_ctx();
    let result = match args {
        [cmd] if cmd == "list" => run_list(&ctx, vault, now),
        [cmd, id] if cmd == "approve" => run_approve(&ctx, vault, id, now, sink),
        [cmd, id, reason] if cmd == "reject" => run_reject(&ctx, vault, id, reason.clone(), now, sink),
        [] => Err(BrainApiError::InvalidInput("no command given — expected one of: list, approve <id>, reject <id> <reason>".to_string())),
        [cmd, ..] => Err(BrainApiError::InvalidInput(format!("unknown command '{cmd}' — expected one of: list, approve <id>, reject <id> <reason>"))),
    };
    let tool = args.first().map(String::as_str).unwrap_or("unknown");
    record_tool_call(sink, tool, allowed_from_result(&result), now, ctx.correlation_id);
    result
}

fn run_list(ctx: &RequestContext, vault: &storage::Vault, now: &str) -> Result<String, BrainApiError> {
    let proposals = crate::list_proposals(ctx, vault, now)?;
    if proposals.is_empty() {
        return Ok("no proposals".to_string());
    }
    let mut lines = Vec::with_capacity(proposals.len());
    for proposal in &proposals {
        lines.push(format!("{} [{:?}] from {}", proposal.id, proposal.status(), proposal.originating_identity));
    }
    Ok(lines.join("\n"))
}

fn run_approve(ctx: &RequestContext, vault: &storage::Vault, id: &str, now: &str, sink: &dyn AuditSink) -> Result<String, BrainApiError> {
    let mut noop_pre_register = |_attempt_id: uuid::Uuid, _proposal_id: &str| Ok(());
    let mut noop_record_outcome = |_attempt_id: uuid::Uuid, _result: &Result<storage::CommitResult, BrainApiError>| Ok(());
    let mut hooks = DurableApprovalHooks::noop(&mut noop_pre_register, &mut noop_record_outcome);
    run_approve_core(ctx, vault, id, now, sink, &mut hooks).0
}

fn run_reject(ctx: &RequestContext, vault: &storage::Vault, id: &str, reason: String, now: &str, sink: &dyn AuditSink) -> Result<String, BrainApiError> {
    run_reject_core(ctx, vault, id, reason, now, sink)
}

/// The shared, trusted implementation behind BOTH `run_approve` (today's
/// existing, non-durable path, called with an inert no-op
/// [`DurableApprovalHooks`]) and [`run_cli_durable`]'s own `approve`
/// dispatch arm (called with real, caller-supplied hooks) — the ONE place
/// `parse_id`/`crate::approve_proposal`/the existing permission-decision
/// audit call and output formatting are written, so neither call site
/// duplicates any authorization, parsing, or dispatch logic. Returns both
/// the real command result AND whether `hooks.record_outcome` itself
/// succeeded (`Ok(())` whenever it was never reached, i.e. pre-
/// registration or id-parsing already failed) — `run_approve` discards
/// that second value (its own inert hook can never fail), `run_cli_durable`
/// surfaces it as [`DurableCliOutcome::audit_outcome_write`].
///
/// Generates a fresh `attempt_id` itself (never supplied by any
/// caller) immediately before calling `hooks.pre_register` — a FRESH id
/// for every single call, so two separate attempts against the same
/// proposal (e.g. a retried approval) never share one. If `pre_register`
/// returns `Err`, `crate::approve_proposal` is NEVER called (fail-closed):
/// this function returns `BrainApiError::RuntimeUnavailable` immediately,
/// before any authorization/validation boundary inside `approve_proposal`
/// itself is ever reached.
fn run_approve_core(ctx: &RequestContext, vault: &storage::Vault, id: &str, now: &str, sink: &dyn AuditSink, hooks: &mut DurableApprovalHooks) -> (Result<String, BrainApiError>, Result<(), String>) {
    let id = match parse_id(id) {
        Ok(id) => id,
        Err(err) => return (Err(err), Ok(())),
    };
    let attempt_id = uuid::Uuid::new_v4();
    if let Err(reason) = (hooks.pre_register)(attempt_id, &id.to_string()) {
        return (Err(BrainApiError::RuntimeUnavailable), Err(reason));
    }
    let result = crate::approve_proposal(ctx, vault, &id, now);
    let audit_outcome_write = (hooks.record_outcome)(attempt_id, &result);
    record_permission_decision(sink, "ApproveProposal", allowed_from_result(&result), Some("permission denied"), now, ctx.correlation_id);
    let formatted = result.map(|result| format!("approved {id}: {result:?}"));
    (formatted, audit_outcome_write)
}

fn run_reject_core(ctx: &RequestContext, vault: &storage::Vault, id: &str, reason: String, now: &str, sink: &dyn AuditSink) -> Result<String, BrainApiError> {
    let id = parse_id(id)?;
    let result = crate::reject_proposal(ctx, vault, &id, reason, now);
    record_permission_decision(sink, "RejectProposal", allowed_from_result(&result), Some("permission denied"), now, ctx.correlation_id);
    result?;
    Ok(format!("rejected {id}"))
}

/// Runs one CLI command with the durable audit path (M5 Task 7): the same
/// trusted dispatch as [`run_cli_with_audit`] (`list`/`approve`/`reject`),
/// but `approve` pre-registers an `ApprovalAttempted`-shaped event through
/// `hooks.pre_register` BEFORE calling [`crate::approve_proposal`] (fail-
/// closed: a failed pre-registration means `approve_proposal` is never
/// called at all) and records the real outcome through
/// `hooks.record_outcome` afterward. `reject` NEVER touches either hook —
/// structurally impossible for a rejection to produce a `CommitOutcome`-
/// shaped call, since `run_reject_core` takes no `DurableApprovalHooks`
/// parameter at all. `list` is unchanged.
///
/// This function constructs the SAME internal trusted context
/// ([`trusted_ctx`]) as `run_cli`/`run_cli_with_audit` — there is no
/// parameter here, or anywhere in this crate's public API, through which
/// a caller could supply or influence `write_policy`/`origin`; `hooks`
/// itself sees only plain, already-public data (an attempt id, a
/// proposal id string, and the real `Result` `approve_proposal` already
/// produced), never `RequestContext`/`WritePolicy`/`TrustedLocalToken`
/// (see `tests/layering.rs`'s own compile-time + behavioral proof of
/// this specific property).
pub fn run_cli_durable(args: &[String], vault: &storage::Vault, now: &str, sink: &dyn AuditSink, hooks: &mut DurableApprovalHooks) -> DurableCliOutcome {
    let ctx = trusted_ctx();
    let (result, audit_outcome_write) = match args {
        [cmd] if cmd == "list" => (run_list(&ctx, vault, now), Ok(())),
        [cmd, id] if cmd == "approve" => run_approve_core(&ctx, vault, id, now, sink, hooks),
        [cmd, id, reason] if cmd == "reject" => (run_reject_core(&ctx, vault, id, reason.clone(), now, sink), Ok(())),
        [] => (Err(BrainApiError::InvalidInput("no command given — expected one of: list, approve <id>, reject <id> <reason>".to_string())), Ok(())),
        [cmd, ..] => (Err(BrainApiError::InvalidInput(format!("unknown command '{cmd}' — expected one of: list, approve <id>, reject <id> <reason>"))), Ok(())),
    };
    let tool = args.first().map(String::as_str).unwrap_or("unknown");
    record_tool_call(sink, tool, allowed_from_result(&result), now, ctx.correlation_id);
    DurableCliOutcome { result, audit_outcome_write }
}

fn parse_id(raw: &str) -> Result<ProposalId, BrainApiError> {
    ProposalId::parse(raw).map_err(|_| BrainApiError::InvalidInput("not a valid proposal id".to_string()))
}
