mod python {
    use super::*;

    #[test]
    fn class_declaration_is_class_definition() {
        let tree = PythonParser.parse(b"class Foo:\n    pass\n").unwrap();
        let node = find_first(tree.tree().root_node(), "class_definition").expect("class_definition must exist");
        assert_eq!(kind_of(node), "class_definition");
    }

    #[test]
    fn function_declaration_is_function_definition() {
        let tree = PythonParser.parse(b"def foo():\n    pass\n").unwrap();
        assert!(find_first(tree.tree().root_node(), "function_definition").is_some());
    }

    #[test]
    fn method_is_the_same_node_kind_as_a_free_function() {
        // Confirmed load-bearing: extract/python.rs's own kind_hint
        // does not distinguish "method" from "free function" because
        // the grammar does not either.
        let tree = PythonParser.parse(b"class Foo:\n    def bar(self):\n        pass\n").unwrap();
        let method = find_first(tree.tree().root_node(), "function_definition").unwrap();
        assert_eq!(kind_of(method), "function_definition");
    }

    #[test]
    fn plain_call_is_call_with_identifier_callee() {
        let tree = PythonParser.parse(b"foo()\n").unwrap();
        let call = find_first(tree.tree().root_node(), "call").expect("call must exist");
        let callee = call.child(0).unwrap();
        assert_eq!(kind_of(callee), "identifier");
    }

    #[test]
    fn attribute_call_callee_is_an_attribute_node() {
        let tree = PythonParser.parse(b"obj.foo()\n").unwrap();
        let call = find_first(tree.tree().root_node(), "call").unwrap();
        let callee = call.child(0).unwrap();
        assert_eq!(kind_of(callee), "attribute");
    }

    #[test]
    fn class_base_list_is_argument_list_of_identifiers() {
        // B2-ID-007's own load-bearing shape: class_definition's base
        // list is an argument_list of identifier children.
        let tree = PythonParser.parse(b"class Base:\n    pass\n\n\nclass Derived(Base):\n    pass\n").unwrap();
        let mut top_cursor = tree.tree().root_node().walk();
        let derived = tree.tree().root_node().children(&mut top_cursor).filter(|n| n.kind() == "class_definition").nth(1).unwrap();
        let args = find_first(derived, "argument_list").expect("a base-class clause is an argument_list");
        let mut cursor = args.walk();
        assert!(args.children(&mut cursor).any(|c| c.kind() == "identifier"), "base name must be a direct identifier child");
    }

    #[test]
    fn dotted_base_is_an_attribute_whose_last_identifier_is_the_real_name() {
        // nn.Module shape -- the resolver uses the LAST identifier.
        let tree = PythonParser.parse(b"class Derived(nn.Module):\n    pass\n").unwrap();
        let attribute = find_first(tree.tree().root_node(), "attribute").expect("nn.Module must parse as attribute");
        let mut cursor = attribute.walk();
        let idents: Vec<_> = attribute.children(&mut cursor).filter(|c| c.kind() == "identifier").collect();
        assert_eq!(idents.len(), 2, "attribute must have exactly 2 identifier children (nn, Module)");
    }

    #[test]
    fn import_statement_and_import_from_statement_are_distinct_kinds() {
        let plain = PythonParser.parse(b"import os\n").unwrap();
        assert!(find_first(plain.tree().root_node(), "import_statement").is_some());
        let from_form = PythonParser.parse(b"from os import path\n").unwrap();
        assert!(find_first(from_form.tree().root_node(), "import_from_statement").is_some());
    }

    #[test]
    fn self_attribute_assignment_is_assignment_with_attribute_left_side() {
        // Field extraction's own load-bearing shape (self.x = ...).
        let tree = PythonParser.parse(b"class Foo:\n    def __init__(self):\n        self.x = 1\n").unwrap();
        let assignment = find_first(tree.tree().root_node(), "assignment").expect("assignment must exist");
        let left = assignment.child(0).unwrap();
        assert_eq!(kind_of(left), "attribute");
    }
}

