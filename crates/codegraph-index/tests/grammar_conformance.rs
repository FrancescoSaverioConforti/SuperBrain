mod csharp {
    use super::*;

    #[test]
    fn class_and_interface_declaration_are_distinct_kinds() {
        let tree = CSharpParser.parse(b"class C {}\ninterface I {}\n").unwrap();
        let root = tree.tree().root_node();
        assert!(find_first(root, "class_declaration").is_some());
        assert!(find_first(root, "interface_declaration").is_some());
    }

    #[test]
    fn method_declaration_exposes_distinct_named_name_and_returns_fields() {
        // B2-ID-009's own load-bearing shape.
        let tree = CSharpParser.parse(b"class C { public PolicyBuilder Handle() => null; }\n").unwrap();
        let method = find_first(tree.tree().root_node(), "method_declaration").unwrap();
        let name_field = method.child_by_field_name("name").unwrap();
        let returns_field = method.child_by_field_name("returns").unwrap();
        assert_eq!(name_field.utf8_text(b"class C { public PolicyBuilder Handle() => null; }").unwrap(), "Handle");
        assert_eq!(returns_field.utf8_text(b"class C { public PolicyBuilder Handle() => null; }").unwrap(), "PolicyBuilder");
        assert_eq!(name_field.kind(), "identifier");
        assert_eq!(returns_field.kind(), "identifier", "a simple non-generic return type is ALSO a bare identifier -- the exact B2-ID-009 collision shape");
    }

    #[test]
    fn base_list_does_not_syntactically_distinguish_class_from_interface() {
        let tree = CSharpParser.parse(b"class Base {}\ninterface IFoo {}\nclass Derived : Base, IFoo {}\n").unwrap();
        let base_list = find_first(tree.tree().root_node(), "base_list").expect("base_list must exist");
        let mut cursor = base_list.walk();
        let idents: Vec<_> = base_list.children(&mut cursor).filter(|c| c.kind() == "identifier").collect();
        assert_eq!(idents.len(), 2, "both the base class and the interface are plain identifier children -- C# syntax never distinguishes them, unlike TypeScript's extends/implements");
    }

    #[test]
    fn partial_modifier_is_a_fixed_lexical_terminal() {
        // B2-ID-010's own load-bearing shape.
        let tree = CSharpParser.parse(b"partial class C {}\n").unwrap();
        let class_decl = find_first(tree.tree().root_node(), "class_declaration").unwrap();
        let mut cursor = class_decl.walk();
        let modifier = class_decl.children(&mut cursor).find(|c| c.kind() == "modifier").expect("a modifier node must exist");
        let mut mod_cursor = modifier.walk();
        let keyword = modifier.children(&mut mod_cursor).next().unwrap();
        assert_eq!(keyword.kind(), "partial");
    }

    #[test]
    fn file_scoped_and_block_scoped_namespace_are_distinct_kinds() {
        let file_scoped = CSharpParser.parse(b"namespace A;\nclass C {}\n").unwrap();
        assert!(find_first(file_scoped.tree().root_node(), "file_scoped_namespace_declaration").is_some());
        let block_scoped = CSharpParser.parse(b"namespace A { class C {} }\n").unwrap();
        assert!(find_first(block_scoped.tree().root_node(), "namespace_declaration").is_some());
    }

    #[test]
    fn bare_generic_call_callee_is_a_direct_generic_name_node() {
        // B2-ID-011's own load-bearing shape.
        let tree = CSharpParser.parse(b"class C { void Foo<T>() {} void Bar() { Foo<int>(); } }\n").unwrap();
        let call = find_first(tree.tree().root_node(), "invocation_expression").expect("invocation_expression must exist");
        let callee = call.child(0).unwrap();
        assert_eq!(kind_of(callee), "generic_name");
        let mut cursor = callee.walk();
        let name_child = callee.children(&mut cursor).find(|c| c.kind() == "identifier").unwrap();
        assert_eq!(name_child.utf8_text(b"class C { void Foo<T>() {} void Bar() { Foo<int>(); } }").unwrap(), "Foo");
    }

    #[test]
    fn receiver_qualified_generic_call_callee_is_member_access_ending_in_generic_name() {
        let src = b"class C { void Foo<T>() {} }\nclass D { void Bar(C c) { c.Foo<int>(); } }\n";
        let tree = CSharpParser.parse(src).unwrap();
        let call = find_first(tree.tree().root_node(), "invocation_expression").unwrap();
        let callee = call.child(0).unwrap();
        assert_eq!(kind_of(callee), "member_access_expression");
        let mut cursor = callee.walk();
        let last_name_child = callee.children(&mut cursor).filter(|c| matches!(c.kind(), "identifier" | "generic_name")).last().unwrap();
        assert_eq!(last_name_child.kind(), "generic_name");
    }

    #[test]
    fn type_parameter_list_is_its_own_distinct_unambiguous_node_kind() {
        // B2-ID-010's own generic_arity_of load-bearing shape.
        let tree = CSharpParser.parse(b"class C<T> {}\n").unwrap();
        let class_decl = find_first(tree.tree().root_node(), "class_declaration").unwrap();
        let mut cursor = class_decl.walk();
        assert!(class_decl.children(&mut cursor).any(|c| c.kind() == "type_parameter_list"));
    }
}

