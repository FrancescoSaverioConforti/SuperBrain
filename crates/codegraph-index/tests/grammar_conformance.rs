mod javascript_typescript {
    use super::*;

    #[test]
    fn js_class_heritage_has_only_extends_no_implements_keyword() {
        let tree = JavaScriptParser.parse(b"class Base {}\nclass Derived extends Base {}\n").unwrap();
        let heritage = find_first(tree.tree().root_node(), "class_heritage").expect("class_heritage must exist");
        // Plain JS grammar has no implements_clause node kind at all.
        assert!(find_first(heritage, "implements_clause").is_none(), "plain JavaScript's grammar has no implements keyword at all");
    }

    #[test]
    fn ts_class_heritage_can_carry_both_extends_clause_and_implements_clause() {
        let tree = TypeScriptParser.parse(b"class Base {}\ninterface IFoo {}\nclass Derived extends Base implements IFoo {}\n").unwrap();
        let heritage = find_first(tree.tree().root_node(), "class_heritage").expect("class_heritage must exist");
        assert!(find_first(heritage, "extends_clause").is_some());
        assert!(find_first(heritage, "implements_clause").is_some());
    }

    #[test]
    fn tsx_parses_jsx_as_a_distinct_element_node_kind() {
        let tree = TsxParser.parse(b"function Foo() { return <div />; }\n").unwrap();
        assert!(find_first(tree.tree().root_node(), "jsx_self_closing_element").is_some(), "JSX composition has its own node kind this pipeline does not model as a typed edge (the documented JSX-composition gap)");
    }

    #[test]
    fn member_expression_callee_ends_in_property_identifier() {
        let tree = JavaScriptParser.parse(b"const obj = { foo() {} };\nobj.foo();\n").unwrap();
        let call = find_first(tree.tree().root_node(), "call_expression").unwrap();
        let callee = call.child(0).unwrap();
        assert_eq!(kind_of(callee), "member_expression");
        let mut cursor = callee.walk();
        let last = callee.children(&mut cursor).filter(|c| c.kind() == "property_identifier").last();
        assert!(last.is_some());
    }

    #[test]
    fn destructured_parameter_is_an_object_pattern_not_a_plain_identifier_parameter() {
        // CRC-002's own load-bearing shape: this IS visible in the
        // AST (the grammar distinguishes it perfectly well) -- the
        // gap is that resolve_calls never consults it, not that the
        // grammar hides the information.
        let tree = JavaScriptParser.parse(b"function Child({ handleSubmit }) { handleSubmit(); }\n").unwrap();
        let params = find_first(tree.tree().root_node(), "formal_parameters").unwrap();
        assert!(find_first(params, "object_pattern").is_some(), "a destructured parameter is a real, distinguishable object_pattern node -- CRC-002 is a resolver gap, not a parser limitation");
    }
}
