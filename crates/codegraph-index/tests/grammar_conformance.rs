mod cpp {
    use super::*;

    #[test]
    fn class_and_struct_specifier_are_distinct_kinds() {
        let tree = CppParser.parse(b"class C {};\nstruct S {};\n").unwrap();
        let root = tree.tree().root_node();
        assert!(find_first(root, "class_specifier").is_some());
        assert!(find_first(root, "struct_specifier").is_some());
    }

    #[test]
    fn free_function_and_method_name_live_one_level_deeper_inside_function_declarator() {
        let free = CppParser.parse(b"int foo() { return 0; }\n").unwrap();
        let declarator = find_first(free.tree().root_node(), "function_declarator").unwrap();
        let mut cursor = declarator.walk();
        assert!(declarator.children(&mut cursor).any(|c| c.kind() == "identifier"), "a free function's name is a plain identifier inside function_declarator");

        let method = CppParser.parse(b"class C { int bar() { return 0; } };\n").unwrap();
        let method_declarator = find_first(method.tree().root_node(), "function_declarator").unwrap();
        let mut cursor = method_declarator.walk();
        assert!(method_declarator.children(&mut cursor).any(|c| c.kind() == "field_identifier"), "a method's name is a field_identifier, NOT a plain identifier, inside the SAME function_declarator node kind");
    }

    #[test]
    fn out_of_class_qualified_definition_name_is_a_qualified_identifier_not_a_plain_one() {
        // The documented, confirmed-omitted (not misnamed) gap.
        let tree = CppParser.parse(b"int S::method(int x) { return x; }\n").unwrap();
        let declarator = find_first(tree.tree().root_node(), "function_declarator").unwrap();
        let first_child = declarator.child(0).unwrap();
        assert_eq!(first_child.kind(), "qualified_identifier", "S::method's own name position is qualified_identifier, a DIFFERENT kind than identifier/field_identifier -- this is why the current extractor omits it rather than misnaming it");
    }

    #[test]
    fn base_class_clause_does_not_syntactically_distinguish_class_from_interface() {
        let tree = CppParser.parse(b"class Base {};\nclass Derived : public Base {};\n").unwrap();
        let clause = find_first(tree.tree().root_node(), "base_class_clause").expect("base_class_clause must exist");
        assert!(find_first(clause, "type_identifier").is_some());
    }

    #[test]
    fn bare_template_call_callee_is_a_direct_template_function_node() {
        // B2-ID-011's own C++ load-bearing shape.
        let tree = CppParser.parse(b"void foo() { bar<int>(); }\n").unwrap();
        let call = find_first(tree.tree().root_node(), "call_expression").expect("call_expression must exist");
        let callee = call.child(0).unwrap();
        assert_eq!(kind_of(callee), "template_function");
    }

    #[test]
    fn receiver_qualified_template_call_callee_ends_in_template_method() {
        let src = b"class C { public: void bar() {} };\nvoid foo(C c) { c.bar<int>(); }\n";
        let tree = CppParser.parse(src).unwrap();
        let call = find_first(tree.tree().root_node(), "call_expression").unwrap();
        let callee = call.child(0).unwrap();
        assert_eq!(kind_of(callee), "field_expression");
        let mut cursor = callee.walk();
        let last_name_child = callee.children(&mut cursor).filter(|c| matches!(c.kind(), "field_identifier" | "template_method")).last().unwrap();
        assert_eq!(last_name_child.kind(), "template_method");
    }

    #[test]
    fn namespace_qualified_call_callee_is_a_qualified_identifier_not_covered_by_the_callee_name_match_arms() {
        // The NEW residual limitation B2-ID-011's own independent
        // review found, pinned directly at the grammar level.
        let tree = CppParser.parse(b"namespace ns { void foo() {} }\nvoid caller() { ns::foo(); }\n").unwrap();
        let call = find_first(tree.tree().root_node(), "call_expression").unwrap();
        let callee = call.child(0).unwrap();
        assert_eq!(kind_of(callee), "qualified_identifier", "ns::foo() is a qualified_identifier -- NOT one of the kinds callee_name's own match arms (identifier/generic_name/template_function/attribute/field_expression/member_expression/member_access_expression) recognize, confirming this gap is orthogonal to B2-ID-011's own fix");
    }
}

