mod rust {
    use super::*;

    #[test]
    fn struct_enum_trait_are_distinct_item_kinds() {
        let tree = RustParser.parse(b"struct S;\nenum E { A }\ntrait T {}\n").unwrap();
        let root = tree.tree().root_node();
        assert!(find_first(root, "struct_item").is_some());
        assert!(find_first(root, "enum_item").is_some());
        assert!(find_first(root, "trait_item").is_some());
    }

    #[test]
    fn function_item_is_the_same_kind_for_free_functions_and_methods() {
        let free = RustParser.parse(b"fn foo() {}\n").unwrap();
        assert!(find_first(free.tree().root_node(), "function_item").is_some());
        let method = RustParser.parse(b"struct S;\nimpl S {\n    fn bar(&self) {}\n}\n").unwrap();
        let impl_block = find_first(method.tree().root_node(), "impl_item").unwrap();
        assert!(find_first(impl_block, "function_item").is_some(), "a method inside impl is the SAME node kind, function_item");
    }

    #[test]
    fn impl_item_exposes_named_trait_and_type_fields() {
        // B2-ID-008's own load-bearing shape.
        let tree = RustParser.parse(b"trait T {}\nstruct S;\nimpl T for S {}\n").unwrap();
        let impl_block = find_first(tree.tree().root_node(), "impl_item").unwrap();
        assert!(impl_block.child_by_field_name("trait").is_some(), "impl_item must expose a named 'trait' field for a trait impl");
        assert!(impl_block.child_by_field_name("type").is_some(), "impl_item must always expose a named 'type' field");
    }

    #[test]
    fn plain_call_callee_is_a_direct_identifier() {
        let tree = RustParser.parse(b"fn foo() {}\nfn bar() { foo(); }\n").unwrap();
        let call = find_first(tree.tree().root_node(), "call_expression").expect("call_expression must exist");
        let callee = call.child(0).unwrap();
        assert_eq!(kind_of(callee), "identifier");
    }

    #[test]
    fn macro_invocation_argument_is_an_opaque_token_tree() {
        // The documented macro-call-opacity gap's own grammar root
        // cause: a macro's own arguments are never real expression
        // nodes to tree-sitter.
        let tree = RustParser.parse(b"fn add(a: i32, b: i32) -> i32 { a + b }\nfn uses() { assert_eq!(add(1, 2), 3); }\n").unwrap();
        let macro_call = find_first(tree.tree().root_node(), "macro_invocation").expect("macro_invocation must exist");
        let token_tree = find_first(macro_call, "token_tree").expect("a macro's own arguments are an opaque token_tree");
        // Confirm there is NO real call_expression INSIDE the macro's
        // own token_tree -- this is the exact structural fact that
        // makes add(1, 2) invisible to resolve_calls.
        assert!(find_first(token_tree, "call_expression").is_none(), "tree-sitter does not expand macros -- a call inside one's arguments is never a real call_expression node");
    }
}

